-- pet_policy 에 칸마다 그 값을 만든 소스를 담습니다.
--
-- batch 조회가 근거를 고를 때 씁니다.
-- policy_evidence 는 소스마다 제 근거를 가지므로 병합에서 진 소스의 근거도 남아 있습니다.
-- 칸 이름으로만 고르면 관리자가 정정한 값 옆에 옛 공공 소스의 문구가 출처로 뜨고,
-- 공공 소스끼리 갈린 칸에서는 최종 값과 반대 말을 하는 근거가 함께 붙습니다.
--
-- 모양은 조건 이름을 키로, 소스 이름 목록을 값으로 둡니다.
--   {"scope": ["PET_TOUR"], "excludedZones": ["PET_TOUR", "CULTURE_CSV"]}
--
-- OWNER · MANUAL 행이 이기면 스무 칸 전부 그 소스입니다.
-- 공공 3종이면 값 칸은 처음 값을 말한 소스, 목록 칸은 합집합에 원소를 보탠 소스 전부입니다.
-- 아무 소스도 말하지 않은 칸은 키가 없습니다.
--
-- 병합이 값을 고르는 순회에서 함께 적으므로 값과 어긋날 수 없습니다.
-- 읽을 때 소스 행을 불러 다시 계산하는 방식은 택하지 않았습니다.
-- 저장된 값과 다시 계산한 승자로 결론이 둘이 되고 조회마다 쿼리가 하나 늘기 때문입니다.
-- 근거 행에 채택 여부를 적는 방식도 택하지 않았습니다.
-- 근거 표는 extract 가 소스별로 갈아 끼우는 원재료라 병합의 결론을 거기 적으면
-- 두 쓰기 경로가 한 표에서 만나고, 근거가 없는 칸은 승자를 적을 자리가 없습니다.

ALTER TABLE pet_policy
    ADD COLUMN field_sources jsonb NOT NULL DEFAULT '{}'::jsonb;

-- 기본값은 이미 있는 행을 위한 것입니다.
--
-- 그 행들은 승자가 비어 근거 없이 조회되다가 그 장소가 다시 병합될 때 채워집니다.
-- 틀린 근거가 아니라 빠진 근거가 되는 쪽이라 안전합니다.
-- 승자는 병합 규칙으로만 계산되므로 이 스크립트에서 채울 수 없습니다.
--
-- 지금 이 저장소의 데이터베이스에는 해당하는 행이 없습니다.
-- 그러나 마이그레이션은 어느 데이터베이스에서든 돌아야 합니다.

COMMENT ON COLUMN pet_policy.field_sources IS
    '칸마다 그 값을 만든 소스. 조건 이름을 키로 소스 이름 목록을 담습니다. batch 가 근거를 고를 때 씁니다.';

-- V20 의 주석 둘을 바로잡습니다.
--
-- 적용된 마이그레이션 파일은 고치면 체크섬이 달라져 기동이 막히므로
-- 파일은 그대로 두고 데이터베이스에 남는 컬럼 설명으로 바로잡습니다.
--
-- ① pet_policy.source_priority
--    V20 은 필드별 출처를 policy_evidence 가 갖고 "출처: 고캠핑" 한 줄도 그쪽에서 나온다고 적었습니다.
--    근거 표에는 진 소스의 근거도 들어 있어 성립하지 않으며, 필드별 출처는 field_sources 가 갖습니다.
--
-- ② policy_evidence.field_name
--    V20 은 pet_policy 의 컬럼 이름이 들어간다고 적었습니다.
--    실제로 들어가는 것은 조건 이름(camelCase)이며 bulk 요청이 그 밖의 이름을 400 으로 막습니다.
--    컬럼 이름을 계약에 쓰면 컬럼을 바꾸는 순간 API 가 깨지기 때문입니다.

COMMENT ON COLUMN pet_policy.source_priority IS
    '이 병합에서 최상위로 이긴 티어. 사람이 손댄 값인지를 관리자 목록에서 거르는 용도입니다. 필드별 출처는 field_sources 가 갖습니다.';

COMMENT ON COLUMN policy_evidence.field_name IS
    '어느 조건의 근거인지. 조건 이름(camelCase)이며 DB 컬럼 이름이 아닙니다.';
