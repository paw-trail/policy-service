-- policy_conflict 에 어느 소스의 것인지를 담습니다.
--
-- 소스 내 어긋남(INTRA_SOURCE)은 extract 가 소스별로 보내므로
-- 재추출할 때 그 소스의 것만 갈아 끼워야 합니다.
-- 담을 칸이 없으면 장소 전체를 지우게 되는데, 그러면 이번 요청에 없는
-- 다른 소스의 어긋남 기록까지 사라지고 되살릴 방법이 없습니다.
--
-- policy_evidence 가 이미 같은 컬럼을 갖고 있습니다.
-- 근거와 소스 내 어긋남은 둘 다 한 소스의 원문에서 나온 것이라 모양이 같아야 합니다.
--
-- 얻는 것이 하나 더 있습니다.
-- 지금까지는 어느 소스가 자기모순이었는지를 알 길이 없었습니다.
-- 고캠핑에서 필드값과 본문이 다른 말을 하는 경우가 28건 확인됐는데,
-- 관리자가 "이 소스 데이터가 원래 이렇다" 를 보려면 이 값이 필요합니다.

ALTER TABLE policy_conflict
    ADD COLUMN source varchar(20);

COMMENT ON COLUMN policy_conflict.source IS
    'INTRA_SOURCE 면 그 소스. CROSS_SOURCE 는 소스 여럿에 걸쳐 있어 NULL 입니다.';

-- 이 스크립트가 돌기 전에 쌓인 소스 내 어긋남은 지웁니다.
--
-- 그 행들은 source 가 비어 있는데, 갈아 끼우는 삭제가
-- place_id 와 source 로 걸기 때문에 영영 지워지지 않습니다.
-- 재추출할 때마다 옛 행이 남은 채 새 행이 쌓여 같은 자리에 어긋남이 둘 보입니다.
--
-- 값을 되살릴 수는 없습니다.
-- source_values 에 담기는 것이 "필드값이 이렇고 본문이 저렇다" 라서
-- 어느 소스였는지가 그 안에 없습니다.
--
-- 지워도 되는 이유는 extract 가 다시 보내면 채워지기 때문입니다.
-- 이 표는 원본이 아니라 뽑아낸 결과이며, 원본은 raw_document 가 가집니다.
--
-- 지금 이 저장소의 데이터베이스에는 해당하는 행이 없습니다.
-- V20 과 V21 이 한 번에 적용됐기 때문입니다.
-- 그러나 마이그레이션은 어느 데이터베이스에서든 돌아야 하고,
-- 이미 V20 만 적용된 곳이 있으면 그쪽에서 실제로 걸립니다.
DELETE FROM policy_conflict
WHERE conflict_type = 'INTRA_SOURCE';

