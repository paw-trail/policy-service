-- pet_policy 에 batch 가 내보내는 근거의 지문을 담습니다.
--
-- 재병합이 조건 값은 같아도 근거가 바뀌었는지를 알아내는 데 씁니다.
-- 근거 문구는 카드 한 줄 · 항목별 이유로 화면에 나가므로 근거만 바뀌어도 판이 올라야 하고,
-- 판이 오르면 policy.changed 가 나가 verdict 가 캐시해 둔 근거를 지웁니다.
--
-- 옛 근거와 직접 비교하지 않고 지문을 남기는 이유는 적재 순서 때문입니다.
-- 적재는 소스의 근거를 지운 뒤 다시 넣고 청크 끝에 재병합하므로,
-- 재병합 시점에는 옛 근거가 이미 남아 있지 않습니다.
--
-- 지문은 SHA-256 을 소문자 16진수 64자로 담습니다.
-- 칸마다 이긴 소스의 근거를 batch 와 같은 규칙으로 골라 늘어놓은 뒤 뜹니다.
-- 근거 식별자와 만든 시각은 넣지 않으므로 같은 근거를 다시 보내면 같은 지문이 나옵니다.

ALTER TABLE pet_policy
    ADD COLUMN evidence_digest varchar(64);

-- null 을 허용하는 것은 이미 있는 행을 위한 것입니다.
--
-- 지문은 병합 규칙과 근거 표를 함께 봐야 나오므로 이 스크립트에서 채울 수 없습니다.
-- 그 행들은 다음 재병합 때 지문이 채워지며, 그때는 비교할 옛 지문이 없어 판을 올리지 않습니다.
-- 한꺼번에 판을 올리면 근거가 그대로인 장소에도 이벤트가 나가기 때문입니다.
--
-- 지금 이 저장소의 데이터베이스에는 해당하는 행이 없습니다.
-- 그러나 마이그레이션은 어느 데이터베이스에서든 돌아야 합니다.

COMMENT ON COLUMN pet_policy.evidence_digest IS
    'batch 가 내보내는 근거의 지문(SHA-256 16진수 64자). 재병합이 근거가 바뀌었는지 알아내 판을 올리는 데 씁니다. null 이면 V24 이전에 만들어져 아직 다시 병합되지 않은 행입니다.';

-- policy_version 의 뜻이 넓어졌습니다.
--
-- 전에는 조건 · 충돌 여부 · 최상위 티어가 바뀔 때 올랐고, 이제 batch 가 내보내는 근거가 바뀔 때도 오릅니다.
-- 오를 때마다 policy.changed 가 나가므로 받는 쪽이 판을 캐시 키로 쓸 수 있습니다.

COMMENT ON COLUMN pet_policy.policy_version IS
    'batch 가 내보내는 것(조건 · 충돌 여부 · 최상위 티어 · 근거)의 판. 오를 때마다 policy.changed 가 나갑니다.';
