package com.pawtrail.policy.domain.enums;

/**
 * 장소 전체가 되는지 일부 구역만 되는지입니다.
 *
 * 판정의 첫 축입니다.
 * 여기가 갈리면 다른 조건을 다 만족해도 결과가 달라집니다.
 */
public enum Scope {

    // 장소 전체에서 동반할 수 있음
    ALL_AREA,

    // 일부 구역만 됨
    //
    // 공사 데이터에서 40% 가 이 값임
    // 어느 구역인지는 excluded_zones · allowed_zones_only 가 담음
    PARTIAL,

    // 동반할 수 없음
    //
    // extract 가 공사 동반 가능 동물 "불가" · 고캠핑 "불가능" · 문화정보원 동반 N 을 이 값으로 적고
    // 실내 · 실외도 false 로 함께 적음
    // 불가를 실내 · 실외 칸에만 적으면 "일부 구역 가능" 을 말한 다른 출처와 칸이 달라
    // 정면으로 갈리는데도 충돌로 잡히지 않음 — 이 값이 범위 칸에서 부딪히게 함
    NONE,

    // 원문에 범위를 가를 근거가 없음
    //
    // NULL 과 다름
    // NULL 은 이 필드를 아예 못 뽑은 것이고, 이 값은 뽑아 봤으나 모른다는 뜻임
    // extract 는 이 값을 쓰지 않음 — 모르면 NULL 로 둠
    // 값이라 다른 출처의 전 구역 · 일부 구역과 가짜 충돌을 내기 때문임
    UNKNOWN
}
